from datetime import datetime, timezone
from io import BytesIO
from typing import Any
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle


class SecurityReportGenerator:
    """Generates executive JSON and downloadable PDF security assessment reports."""

    @staticmethod
    def build_json_payload(
        org_name: str,
        generated_by: str,
        overview: dict[str, Any],
        findings: list[dict[str, Any]],
        threats: list[dict[str, Any]],
    ) -> dict[str, Any]:
        return {
            "report_metadata": {
                "platform": "VaultMesh Cloud Security Posture Management",
                "organization": org_name,
                "generated_by": generated_by,
                "generated_at_utc": datetime.now(timezone.utc).isoformat(),
                "disclaimer": "Informational security posture assessment. Does not constitute formal compliance certification.",
            },
            "executive_summary": {
                "security_score": overview.get("security_score"),
                "aws_accounts_connected": overview.get("aws_accounts_connected", 0),
                "monitored_resources": overview.get("monitored_resources", 0),
                "total_open_findings": overview.get("total_open_findings", 0),
                "severity_distribution": overview.get("findings_by_severity", {}),
                "threat_alerts_detected": len(threats),
            },
            "findings": findings,
            "threat_events": threats,
        }

    @staticmethod
    def build_pdf_bytes(report_data: dict[str, Any]) -> bytes:
        buffer = BytesIO()
        doc = SimpleDocTemplate(
            buffer,
            pagesize=A4,
            rightMargin=36,
            leftMargin=36,
            topMargin=36,
            bottomMargin=36,
        )
        styles = getSampleStyleSheet()
        title_style = ParagraphStyle(
            "VMTitle",
            parent=styles["Heading1"],
            fontSize=18,
            textColor=colors.HexColor("#0F172A"),
            spaceAfter=6,
        )
        h2_style = ParagraphStyle(
            "VMH2",
            parent=styles["Heading2"],
            fontSize=13,
            textColor=colors.HexColor("#0284C7"),
            spaceBefore=12,
            spaceAfter=6,
        )
        body_style = ParagraphStyle(
            "VMBody",
            parent=styles["BodyText"],
            fontSize=9.5,
            leading=13,
        )

        meta = report_data["report_metadata"]
        summary = report_data["executive_summary"]
        sev = summary.get("severity_distribution", {})

        story = [
            Paragraph("VaultMesh Security Assessment Report", title_style),
            Paragraph(
                f"Organization: <b>{meta['organization']}</b> | Generated By: {meta['generated_by']} | UTC: {meta['generated_at_utc']}",
                body_style,
            ),
            Spacer(1, 10),
            Paragraph("1. Executive Summary", h2_style),
        ]

        summary_table = Table(
            [
                ["Metric", "Value"],
                ["Overall Security Score", f"{summary.get('security_score', 'N/A')}%"],
                ["Connected AWS Accounts", str(summary.get("aws_accounts_connected", 0))],
                ["Monitored Cloud Resources", str(summary.get("monitored_resources", 0))],
                ["Open Findings (Total)", str(summary.get("total_open_findings", 0))],
                [
                    "Severity Breakdown",
                    f"Critical: {sev.get('CRITICAL', 0)} | High: {sev.get('HIGH', 0)} | Medium: {sev.get('MEDIUM', 0)} | Low: {sev.get('LOW', 0)}",
                ],
                ["CloudTrail Threat Alerts", str(summary.get("threat_alerts_detected", 0))],
            ],
            colWidths=[210, 300],
        )
        summary_table.setStyle(
            TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0F172A")),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("FONTSIZE", (0, 0), (-1, -1), 9),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
                ("BACKGROUND", (0, 1), (-1, -1), colors.HexColor("#F8FAFC")),
                ("PADDING", (0, 0), (-1, -1), 6),
            ])
        )
        story.append(summary_table)
        story.append(Spacer(1, 12))

        story.append(Paragraph("2. Detailed Findings & Remediation Guidance", h2_style))
        findings = report_data.get("findings", [])
        if not findings:
            story.append(Paragraph("No security findings recorded for this assessment.", body_style))
        else:
            for idx, f in enumerate(findings, start=1):
                story.append(
                    Paragraph(
                        f"<b>{idx}. [{f['severity']}] {f['title']}</b> ({f['finding_uid']} — Status: {f['status']})",
                        body_style,
                    )
                )
                story.append(Paragraph(f"Resource: <font face='Courier'>{f['resource_arn']}</font>", body_style))
                story.append(Paragraph(f"Recommended Fix: {f['remediation_summary']}", body_style))
                story.append(Spacer(1, 6))

        story.append(Spacer(1, 10))
        story.append(Paragraph(f"<i>Note: {meta['disclaimer']}</i>", body_style))

        doc.build(story)
        return buffer.getvalue()
